CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    room_id BIGINT NOT NULL,
    user_id BIGINT,
    client_message_id TEXT,
    content TEXT NOT NULL DEFAULT '',
    message_type SMALLINT NOT NULL DEFAULT 1,
    status SMALLINT NOT NULL DEFAULT 1,
    version BIGINT NOT NULL DEFAULT 1,
    reply_to_message_id BIGINT,
    reply_to_message_created_at TIMESTAMPTZ,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    edited_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    deleted_by BIGINT,
    delete_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (client_message_id IS NULL OR length(client_message_id) BETWEEN 1 AND 128),
    CHECK (version >= 1),
    CHECK (jsonb_typeof(metadata) = 'object'),
    CHECK (
        (reply_to_message_id IS NULL AND reply_to_message_created_at IS NULL)
        OR (reply_to_message_id IS NOT NULL AND reply_to_message_created_at IS NOT NULL)
    ),
    PRIMARY KEY (id, created_at),
    UNIQUE (room_id, id, created_at),
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE RESTRICT,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
    FOREIGN KEY (deleted_by) REFERENCES users(id) ON DELETE SET NULL,
    FOREIGN KEY (room_id, reply_to_message_id, reply_to_message_created_at)
        REFERENCES chat_messages(room_id, id, created_at)
        ON DELETE SET NULL (reply_to_message_id, reply_to_message_created_at)
) PARTITION BY RANGE (created_at);

CREATE TABLE IF NOT EXISTS chat_messages_default PARTITION OF chat_messages DEFAULT;
CREATE INDEX IF NOT EXISTS chat_messages_default_idx_room_pagination
    ON chat_messages_default(room_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS chat_messages_default_idx_user_created
    ON chat_messages_default(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS chat_messages_default_idx_created_at
    ON chat_messages_default(created_at DESC);
CREATE INDEX IF NOT EXISTS chat_messages_default_idx_status
    ON chat_messages_default(room_id, status, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS chat_messages_default_idx_reply_target
    ON chat_messages_default(reply_to_message_id, reply_to_message_created_at);
CREATE INDEX IF NOT EXISTS chat_messages_default_idx_playback_media
    ON chat_messages_default(
        room_id,
        ((metadata #>> '{playback,media_id}')),
        (
            CASE
                WHEN jsonb_typeof(metadata #> '{playback,position_seconds}') = 'number'
                THEN (metadata #>> '{playback,position_seconds}')::double precision
                ELSE NULL
            END
        ),
        created_at,
        id
    )
    WHERE metadata ? 'playback';
CREATE INDEX IF NOT EXISTS chat_messages_default_idx_playback_playlist_target
    ON chat_messages_default(
        room_id,
        ((metadata #>> '{playback,playlist_id}')),
        ((metadata #>> '{playback,target_hash}')),
        (
            CASE
                WHEN jsonb_typeof(metadata #> '{playback,position_seconds}') = 'number'
                THEN (metadata #>> '{playback,position_seconds}')::double precision
                ELSE NULL
            END
        ),
        created_at,
        id
    )
    WHERE metadata ? 'playback';

CREATE TABLE IF NOT EXISTS chat_message_idempotency (
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    client_message_id TEXT NOT NULL,
    request_hash TEXT NOT NULL,
    message_id BIGINT,
    message_created_at TIMESTAMPTZ,
    event_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (room_id, user_id, client_message_id),
    CHECK (length(client_message_id) BETWEEN 1 AND 128),
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (room_id, message_id, message_created_at)
        REFERENCES chat_messages(room_id, id, created_at) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_chat_message_idempotency_created
    ON chat_message_idempotency(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_message_idempotency_message
    ON chat_message_idempotency(message_id, message_created_at);

CREATE TABLE IF NOT EXISTS chat_message_images (
    id TEXT NOT NULL,
    room_id BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    message_created_at TIMESTAMPTZ NOT NULL,
    storage_backend TEXT NOT NULL,
    object_key TEXT NOT NULL,
    url TEXT,
    mime_type TEXT,
    size_bytes BIGINT,
    width INTEGER,
    height INTEGER,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(id) BETWEEN 1 AND 128),
    CHECK (length(storage_backend) BETWEEN 1 AND 64),
    CHECK (length(object_key) BETWEEN 1 AND 2048),
    CHECK (size_bytes IS NULL OR size_bytes > 0),
    CHECK (width IS NULL OR width > 0),
    CHECK (height IS NULL OR height > 0),
    CHECK (jsonb_typeof(metadata) = 'object'),
    PRIMARY KEY (room_id, message_id, message_created_at, id),
    FOREIGN KEY (room_id, message_id, message_created_at)
        REFERENCES chat_messages(room_id, id, created_at) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_chat_message_images_message
    ON chat_message_images(message_id, message_created_at);
CREATE INDEX IF NOT EXISTS idx_chat_message_images_room
    ON chat_message_images(room_id, created_at DESC);

CREATE TABLE IF NOT EXISTS chat_message_events (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id TEXT NOT NULL UNIQUE,
    room_id BIGINT NOT NULL,
    message_id BIGINT NOT NULL,
    message_created_at TIMESTAMPTZ NOT NULL,
    actor_user_id BIGINT NOT NULL,
    kind SMALLINT NOT NULL,
    message_version BIGINT NOT NULL,
    event_payload JSONB NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (length(event_id) BETWEEN 1 AND 128),
    CHECK (message_version >= 1),
    CHECK (jsonb_typeof(event_payload) = 'object'),
    FOREIGN KEY (room_id, message_id, message_created_at)
        REFERENCES chat_messages(room_id, id, created_at) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_chat_message_events_room_sequence
    ON chat_message_events(room_id, sequence);
CREATE INDEX IF NOT EXISTS idx_chat_message_events_room_occurred
    ON chat_message_events(room_id, occurred_at DESC, sequence DESC);

CREATE TABLE IF NOT EXISTS chat_message_operation_idempotency (
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    client_operation_id TEXT NOT NULL,
    operation_kind SMALLINT NOT NULL,
    request_hash TEXT NOT NULL,
    message_id BIGINT NOT NULL,
    message_created_at TIMESTAMPTZ NOT NULL,
    event_id TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (room_id, user_id, client_operation_id),
    CHECK (length(client_operation_id) BETWEEN 1 AND 128),
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (room_id, message_id, message_created_at)
        REFERENCES chat_messages(room_id, id, created_at) ON DELETE CASCADE,
    FOREIGN KEY (event_id) REFERENCES chat_message_events(event_id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_chat_message_operation_idempotency_message
    ON chat_message_operation_idempotency(room_id, message_id, message_created_at);
CREATE INDEX IF NOT EXISTS idx_chat_message_operation_idempotency_event
    ON chat_message_operation_idempotency(event_id)
    WHERE event_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS chat_read_states (
    room_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    last_read_message_id BIGINT,
    last_read_message_created_at TIMESTAMPTZ,
    last_read_event_id TEXT,
    last_read_event_sequence BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (room_id, user_id),
    CHECK (
        (last_read_message_id IS NULL AND last_read_message_created_at IS NULL)
        OR (last_read_message_id IS NOT NULL AND last_read_message_created_at IS NOT NULL)
    ),
    CHECK (last_read_event_sequence IS NULL OR last_read_event_sequence >= 1),
    FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (room_id, last_read_message_id, last_read_message_created_at)
        REFERENCES chat_messages(room_id, id, created_at)
        ON DELETE SET NULL (last_read_message_id, last_read_message_created_at)
);

CREATE INDEX IF NOT EXISTS idx_chat_read_states_room_updated
    ON chat_read_states(room_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_chat_read_states_message
    ON chat_read_states(last_read_message_id, last_read_message_created_at);
