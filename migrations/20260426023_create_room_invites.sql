CREATE TABLE IF NOT EXISTS room_invites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    code VARCHAR(24) NOT NULL,
    label VARCHAR(100),
    max_uses INTEGER,
    uses_count INTEGER NOT NULL DEFAULT 0,
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    revoked_by BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT room_invites_code_not_empty CHECK (length(trim(code)) > 0),
    CONSTRAINT room_invites_code_length CHECK (char_length(code) = 24),
    CONSTRAINT room_invites_label_not_empty CHECK (label IS NULL OR length(trim(label)) > 0),
    CONSTRAINT room_invites_max_uses_positive CHECK (max_uses IS NULL OR max_uses > 0),
    CONSTRAINT room_invites_uses_count_non_negative CHECK (uses_count >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_room_invites_code ON room_invites(code);
CREATE INDEX IF NOT EXISTS idx_room_invites_room_active
    ON room_invites(room_id, created_at DESC)
    WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_room_invites_created_by
    ON room_invites(created_by, created_at DESC);

CREATE TRIGGER update_room_invites_updated_at
    BEFORE UPDATE ON room_invites
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

COMMENT ON TABLE room_invites IS 'Revocable room invitation links/codes';
COMMENT ON COLUMN room_invites.code IS 'Secret invite code used to join a room';
COMMENT ON COLUMN room_invites.max_uses IS 'Optional maximum number of successful joins';
